                    : "Do you deliver to patient rooms at hospitals serving {$name}?",
                'a' => $es
                    ? "Entregamos en la recepción del hospital, que lleva las flores a la habitación del paciente. Incluya el nombre completo del paciente y, si lo conoce, el número de habitación."
                    : "We deliver to the hospital's front desk, which routes flowers to the patient's room. Include the patient's full name and room number if you have it.",
            ];
        }

        return $items;
    }

    /**
     * Assemble the schema.org JSON-LD graph for a service + city page.
     *
     * Produces a @graph containing a Service node (provider = the florist,
     * areaServed = the city), a Place node per named venue, and a FAQPage built
     * from {@see self::faqItems()}. The caller json_encodes the result into a
     * <script type="application/ld+json"> block, mirroring ProductController.
     *
     * @param string               $service     Service code.
     * @param array<string, mixed> $city        A city record.
     * @param string               $lang        'en' or 'es'.
     * @param array<string, mixed> $services    Service definitions.
     * @param array{
     *     name?: string, telephone?: string, url?: string,
     *     street?: string, city?: string, state?: string, postal?: string,
     *     pageUrl?: string
     * } $business Business NAP + the absolute URL of this page.
     *
     * @return array<string, mixed> A schema.org graph ready for json_encode().
     *
     * @example
     *   $ld = LocalArea::buildJsonLd('funeral', $bixby, 'en', $services, $biz);
     *   $ld['@graph'][0]['@type']; // 'Service'
     */
    public static function buildJsonLd(
        string $service,
        array $city,
        string $lang,
        array $services,
        array $business
    ): array {
        $cityName = (string) $city['name'];
        $state    = (string) ($city['state'] ?? 'OK');

        $provider = [
            '@type'     => 'Florist',
            'name'      => $business['name'] ?? '',
            'telephone' => $business['telephone'] ?? '',
            'url'       => $business['url'] ?? '',
            'address'   => [
                '@type'           => 'PostalAddress',
                'streetAddress'   => $business['street'] ?? '',
                'addressLocality' => $business['city'] ?? 'Tulsa',
                'addressRegion'   => $business['state'] ?? 'OK',
                'postalCode'      => $business['postal'] ?? '',
                'addressCountry'  => 'US',
            ],
        ];

        $serviceNode = [
            '@type'       => 'Service',
            'serviceType' => (string) ($services[$service]['service_type'] ?? 'Flower delivery'),
            'name'        => self::serviceTitle($service, $city, $lang, $services),
            'provider'    => $provider,
            'areaServed'  => [
                '@type'   => 'City',
                'name'    => $cityName,
                'address' => [
                    '@type'           => 'PostalAddress',
                    'addressLocality' => $cityName,
                    'addressRegion'   => $state,
                    'addressCountry'  => 'US',
                ],
            ],
        ];
        if (!empty($business['pageUrl'])) {
            $serviceNode['url'] = $business['pageUrl'];
        }

        $graph = [$serviceNode];

        foreach (self::venues($service, $city, $services) as $venue) {
            $graph[] = [
                '@type'   => 'Place',
                'name'    => $venue['name'],
                'address' => $venue['address'],
            ];
        }

        $faq = self::faqItems($service, $city, $lang);
        if ($faq !== []) {
            $graph[] = [
                '@type'            => 'FAQPage',
                'mainEntity'       => array_map(static fn (array $f): array => [
                    '@type'          => 'Question',
                    'name'           => $f['q'],
                    'acceptedAnswer' => ['@type' => 'Answer', 'text' => $f['a']],
                ], $faq),
            ];
        }

        return ['@context' => 'https://schema.org', '@graph' => $graph];
    }

    /**
     * Validate a city-data array against the field contract.
     *
     * Checks every city has the required scalar keys, a non-empty direction in
     * both languages, and — for any city — well-formed venue records (each with
     * a non-empty name and an address). Returns a flat list of human-readable
     * problems; an empty list means the data is structurally sound.
     *
     * @param array<string, array<string, mixed>> $areas City data to check.
     *
     * @return list<string> Problems found (empty when valid).
     *
     * @example
     *   LocalArea::validateAreas(LocalArea::areas()); // []  (ships clean)
     */
    public static function validateAreas(array $areas): array
    {
        $problems = [];
        if ($areas === []) {
            return ['areas: file is empty'];
        }

        $required = ['name', 'state', 'distance_miles', 'direction_en', 'direction_es'];

        foreach ($areas as $slug => $city) {
            if (!is_string($slug) || !preg_match('/^[a-z0-9-]+$/', $slug)) {
                $problems[] = "city slug '{$slug}': must match [a-z0-9-]";
            }
            foreach ($required as $key) {
                // Note: a strict '' check (not empty()) so legitimate values like
                // distance_miles '0' for the home city are not falsely rejected.
                if (!self::isFilledString($city[$key] ?? null)) {
                    $problems[] = "city '{$slug}': missing or empty '{$key}'";
                }
            }
            foreach (['funeral_homes', 'hospitals'] as $listKey) {
                $list = $city[$listKey] ?? null;
                if (!is_array($list) || $list === []) {
                    $problems[] = "city '{$slug}': '{$listKey}' must be a non-empty list";
                    continue;
                }
                foreach ($list as $i => $venue) {
                    if (!self::isFilledString($venue['name'] ?? null)) {
                        $problems[] = "city '{$slug}' {$listKey}[{$i}]: missing name";
                    }
                    if (!self::isFilledString($venue['address'] ?? null)) {
                        $problems[] = "city '{$slug}' {$listKey}[{$i}]: missing address";
                    }
                }
            }
        }

        return $problems;
    }

    /**
     * Validate a service-definition array against the field contract.
     *
     * @param array<string, array<string, mixed>> $services Service definitions.
     *
     * @return list<string> Problems found (empty when valid).
     */
    public static function validateServices(array $services): array
    {
        $problems = [];
        if ($services === []) {
            return ['services: file is empty'];
        }

        $required = [
            'prefix', 'service_type', 'label_en', 'label_es',
            'title_en', 'title_es', 'meta_en', 'meta_es', 'h1_en', 'h1_es',
        ];

        foreach ($services as $code => $def) {
            foreach ($required as $key) {
                if (!self::isFilledString($def[$key] ?? null)) {
                    $problems[] = "service '{$code}': missing or empty '{$key}'";
                }
            }
            // 'entities', when present, must be a key that exists on city records.
            $entities = $def['entities'] ?? null;
            if ($entities !== null && !in_array($entities, ['funeral_homes', 'hospitals'], true)) {
                $problems[] = "service '{$code}': 'entities' must be null, 'funeral_homes', or 'hospitals'";
            }
        }

        return $problems;
    }

    /**
     * Normalize a language code to the supported set, defaulting to English.
     *
     * @param string $lang Raw language code.
     *
     * @return string 'en' or 'es'.
     */
    private static function lang(string $lang): string
    {
        return $lang === 'es' ? 'es' : 'en';
    }

    /**
     * Whether a value is a non-empty string. Used instead of empty() so that
     * legitimate values such as the string '0' are not treated as missing.
     *
     * @param mixed $value The value to test.
     *
     * @return bool True only for a string that is not ''.
     */
    private static function isFilledString(mixed $value): bool
    {
        return is_string($value) && $value !== '';
    }

    /**
     * Substitute the city name into a single-%s template, tolerating templates
     * that (incorrectly) contain no placeholder.
     *
     * @param string $template A template with at most one %s.
     * @param string $cityName The city display name.
     *
     * @return string The filled string.
     */
    private static function fill(string $template, string $cityName): string
    {
        if (!str_contains($template, '%s')) {
            return $template;
        }
        return sprintf($template, $cityName);
    }
